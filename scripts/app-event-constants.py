#!/usr/bin/env python3
"""Generate or verify the managed App Events constants from the bundled facebook-core AAR.

The C# constants must match com.facebook.appevents.AppEventsConstants of the exact SDK the
package ships. This script reads the constants with `javap -constants` from the restored
facebook-core AAR and either rewrites the C# file (--write) or fails when it drifted (default).

Usage:
  python3 scripts/app-event-constants.py [--write] [--deps <dir with facebook-core-*.aar>]
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DEPS = ROOT / "src/Kapusch.FacebookApisForAndroidComponents/Native/Android/build/deps"
OUTPUT = ROOT / "src/Kapusch.FacebookApisForAndroidComponents/Facebook/FacebookAppEventConstants.cs"
JAVA_CLASS = "com.facebook.appevents.AppEventsConstants"
CONSTANT = re.compile(r'public static final java\.lang\.String (\w+) = "([^"]*)";')

# Upstream EVENT_NAME_PURCHASED is deprecated in favour of logPurchase; keep the constant (it is
# the documented standard event name) but point callers to the dedicated API.
NOTES = {
    "EVENT_NAME_PURCHASED": "Prefer <see cref=\"FacebookAppEvents.LogPurchase\"/>, which adds the currency.",
    "EVENT_NAME_START_TRIAL": "See <see cref=\"FacebookAppEvents.LogStartTrial\"/>.",
    "EVENT_NAME_SUBSCRIBE": "See <see cref=\"FacebookAppEvents.LogSubscribe\"/>.",
    "EVENT_NAME_COMPLETED_REGISTRATION": "See <see cref=\"FacebookAppEvents.LogCompleteRegistration\"/>.",
}


# Words whose casing follows the iOS package (and .NET naming) instead of plain title case, so
# shared code can use the same constant names on both platforms.
WORDS = {"APPLINK": "AppLink", "IPHONE": "IPhone", "IPAD": "IPad"}


def pascal(name: str) -> str:
    return "".join(WORDS.get(part, part[:1].upper() + part[1:].lower()) for part in name.split("_") if part)


def read_constants(deps: Path) -> tuple[str, list[tuple[str, str]]]:
    aars = sorted(deps.glob("facebook-core-*.aar"))
    if len(aars) != 1:
        raise SystemExit(f"Expected exactly one facebook-core AAR in {deps}, found {len(aars)}. Run restore-facebook-aars.sh.")
    aar = aars[0]
    version = aar.stem.removeprefix("facebook-core-")
    with tempfile.TemporaryDirectory() as tmp:
        jar = Path(tmp) / "classes.jar"
        with zipfile.ZipFile(aar) as archive:
            jar.write_bytes(archive.read("classes.jar"))
        output = subprocess.check_output(["javap", "-constants", "-cp", str(jar), JAVA_CLASS], text=True)
    constants = CONSTANT.findall(output)
    if not constants:
        raise SystemExit(f"No String constants found in {JAVA_CLASS}.")
    return version, constants


def render(version: str, constants: list[tuple[str, str]]) -> str:
    groups = {
        "FacebookAppEventNames": ("EVENT_NAME_", "Standard App Events names"),
        "FacebookAppEventParameterNames": ("EVENT_PARAM_", "Standard App Events parameter names"),
        "FacebookAppEventParameterValues": ("EVENT_PARAM_VALUE_", "Canonical App Events parameter values"),
    }
    lines = [
        "// <auto-generated>",
        f"// Generated by scripts/app-event-constants.py from {JAVA_CLASS}",
        f"// in facebook-core {version}. Do not edit by hand: run the script with --write.",
        "// </auto-generated>",
        "",
        "namespace Kapusch.Facebook.Android;",
    ]
    for class_name, (prefix, summary) in groups.items():
        members = []
        for java_name, value in constants:
            if not java_name.startswith(prefix):
                continue
            if prefix == "EVENT_PARAM_" and java_name.startswith("EVENT_PARAM_VALUE_") and java_name != "EVENT_PARAM_VALUE_TO_SUM":
                continue
            if prefix == "EVENT_PARAM_VALUE_" and java_name == "EVENT_PARAM_VALUE_TO_SUM":
                continue
            members.append((pascal(java_name.removeprefix(prefix)), java_name, value))
        lines += [
            "",
            f"/// <summary>{summary}, mirrored from <c>AppEventsConstants</c> of the bundled Facebook Android SDK ({version}).</summary>",
            f"public static class {class_name}",
            "{",
        ]
        for index, (member, java_name, value) in enumerate(members):
            note = NOTES.get(java_name)
            summary_text = f"<c>AppEventsConstants.{java_name}</c>." + (f" {note}" if note else "")
            if index:
                lines.append("")
            lines.append(f"\t/// <summary>{summary_text}</summary>")
            lines.append(f'\tpublic const string {member} = "{value}";')
        lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="rewrite the C# constants file")
    parser.add_argument("--deps", type=Path, default=DEFAULT_DEPS)
    args = parser.parse_args()

    version, constants = read_constants(args.deps)
    expected = render(version, constants)
    if args.write:
        OUTPUT.write_text(expected, encoding="utf-8")
        print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(constants)} constants, facebook-core {version})")
        return 0
    actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if actual != expected:
        print(
            f"{OUTPUT.relative_to(ROOT)} does not match AppEventsConstants of facebook-core {version}. "
            "Run: python3 scripts/app-event-constants.py --write",
            file=sys.stderr,
        )
        return 1
    print(f"App Events constants match facebook-core {version} ({len(constants)} constants)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
